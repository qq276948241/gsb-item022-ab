#!/usr/bin/env node
"use strict";

// 色温脚本的可反复跑检查。直接用子进程调用原来的 色温.js，
// 不自己另写一套换算，也不另起入口。只用 Node 自带功能。

var childProcess = require("child_process");
var path = require("path");

var 脚本路径 = path.join(__dirname, "色温.js");
var 失败人话 = "没法说冷暖：请给出一个不小于零的整数，后面紧跟开\n";

// 期望取自脚本现在的真输出（含末尾换行），逐字写死。
var 用例表 = [
  { 描述: "0开 应打出暖", 参数: ["0开"], 退出码: 0, 标准输出: "暖\n", 标准错误: "" },
  { 描述: "3299开 应打出暖（低于3300）", 参数: ["3299开"], 退出码: 0, 标准输出: "暖\n", 标准错误: "" },
  { 描述: "3300开 应打出中（正好3300算中）", 参数: ["3300开"], 退出码: 0, 标准输出: "中\n", 标准错误: "" },
  { 描述: "5299开 应打出中（到5300之前仍是中）", 参数: ["5299开"], 退出码: 0, 标准输出: "中\n", 标准错误: "" },
  { 描述: "5300开 应打出冷（正好5300算冷）", 参数: ["5300开"], 退出码: 0, 标准输出: "冷\n", 标准错误: "" },
  { 描述: "6500开 应打出冷（再往上还是冷）", 参数: ["6500开"], 退出码: 0, 标准输出: "冷\n", 标准错误: "" },
  { 描述: "缺了单位的 2700 应失败，且是原来那句人话", 参数: ["2700"], 退出码: 2, 标准输出: "", 标准错误: 失败人话 },
  { 描述: "负数的 -5开 应失败，且是原来那句人话", 参数: ["-5开"], 退出码: 2, 标准输出: "", 标准错误: 失败人话 },
  { 描述: "带小数的 3300.5开 应失败，且是原来那句人话", 参数: ["3300.5开"], 退出码: 2, 标准输出: "", 标准错误: 失败人话 },
  { 描述: "空着（给了一个空参数）应失败，且是原来那句人话", 参数: [""], 退出码: 2, 标准输出: "", 标准错误: 失败人话 },
  { 描述: "空着（一个参数都没给）应失败，且是原来那句人话", 参数: [], 退出码: 2, 标准输出: "", 标准错误: 失败人话 },
  { 描述: "参数不是恰好一段（给了两段）应失败，且是原来那句人话", 参数: ["0开", "3300开"], 退出码: 2, 标准输出: "", 标准错误: 失败人话 },
  { 描述: "参数不是恰好一段（一段里夹了空格）应失败，且是原来那句人话", 参数: ["0开 "], 退出码: 2, 标准输出: "", 标准错误: 失败人话 }
];

function 跑一次(参数) {
  return childProcess.spawnSync(process.execPath, [脚本路径].concat(参数), { encoding: "utf8" });
}

function 看样(文本) {
  if (文本 === "") {
    return "空";
  }
  return JSON.stringify(文本);
}

var 失败条目 = [];

用例表.forEach(function (用例) {
  // 同一条连跑两次，打出来的字必须一模一样。
  var 第一遍 = 跑一次(用例.参数);
  var 第二遍 = 跑一次(用例.参数);

  function 记一笔(毛病) {
    失败条目.push("第 " + (用例表.indexOf(用例) + 1) + " 条没过：" + 用例.描述 + "\n    " + 毛病);
  }

  [["第一遍", 第一遍], ["第二遍", 第二遍]].forEach(function (一轮) {
    var 遍名 = 一轮[0];
    var 结果 = 一轮[1];

    if (结果.error) {
      记一笔(遍名 + "脚本根本没跑起来：" + 结果.error.message);
      return;
    }
    if (结果.status !== 用例.退出码) {
      记一笔(遍名 + "退出码是 " + 结果.status + "，期望 " + 用例.退出码);
    }
    if (结果.stdout !== 用例.标准输出) {
      记一笔(遍名 + "标准输出是 " + 看样(结果.stdout) + "，期望 " + 看样(用例.标准输出) + "（注意末尾换行）");
    }
    if (结果.stderr !== 用例.标准错误) {
      记一笔(遍名 + "标准错误是 " + 看样(结果.stderr) + "，期望 " + 看样(用例.标准错误) + "（注意末尾换行）");
    }
  });

  if (
    !第一遍.error && !第二遍.error &&
    (第一遍.status !== 第二遍.status ||
      第一遍.stdout !== 第二遍.stdout ||
      第一遍.stderr !== 第二遍.stderr)
  ) {
    记一笔("连跑两遍打出来的字不一样：" +
      看样(第一遍.stdout) + "/" + 看样(第一遍.stderr) + " 对 " +
      看样(第二遍.stdout) + "/" + 看样(第二遍.stderr));
  }
});

if (失败条目.length > 0) {
  process.stderr.write("检查没全过，一共 " + 失败条目.length + " 处对不上：\n");
  失败条目.forEach(function (条目) {
    process.stderr.write("- " + 条目 + "\n");
  });
  process.exit(1);
}

process.stdout.write("全部 " + 用例表.length + " 条检查通过，每条连跑两遍结果一致。\n");
process.exit(0);
