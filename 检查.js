#!/usr/bin/env node
"use strict";

// 色温.js 的反复检查。只调用原来的脚本，不在这里重写换算。
// 用法：node 检查.js
// 全部通过时退出码为 0；有一条没过就非 0，并指出是哪一条。

const { spawnSync } = require("child_process");
const path = require("path");

const 脚本路径 = path.join(__dirname, "色温.js");
const 出错人话 = "没法说冷暖：请给出一个不小于零的整数，后面紧跟开\n";

function 跑一回(参数列表) {
  const 结果 = spawnSync(process.execPath, [脚本路径].concat(参数列表), {
    encoding: "utf8",
    input: "",
    stdio: ["pipe", "pipe", "pipe"],
  });
  if (结果.error) {
    throw 结果.error;
  }
  return { 退出码: 结果.status, 标准输出: 结果.stdout, 标准错误: 结果.stderr };
}

// 期望与脚本现在的真实输出逐字一致。
const 用例 = [
  { 名: "0开 应打出暖", 参数: ["0开"], 退出码: 0, 标准输出: "暖\n", 标准错误: "" },
  { 名: "3299开 应打出暖", 参数: ["3299开"], 退出码: 0, 标准输出: "暖\n", 标准错误: "" },
  { 名: "3300开 应打出中", 参数: ["3300开"], 退出码: 0, 标准输出: "中\n", 标准错误: "" },
  { 名: "5299开 应打出中", 参数: ["5299开"], 退出码: 0, 标准输出: "中\n", 标准错误: "" },
  { 名: "5300开 应打出冷", 参数: ["5300开"], 退出码: 0, 标准输出: "冷\n", 标准错误: "" },
  { 名: "6500开 应打出冷", 参数: ["6500开"], 退出码: 0, 标准输出: "冷\n", 标准错误: "" },
  { 名: "缺单位的 2700 应失败", 参数: ["2700"], 退出码: "非零", 标准输出: "", 标准错误: 出错人话 },
  { 名: "负数的 -5开 应失败", 参数: ["-5开"], 退出码: "非零", 标准输出: "", 标准错误: 出错人话 },
  { 名: "带小数的 3300.5开 应失败", 参数: ["3300.5开"], 退出码: "非零", 标准输出: "", 标准错误: 出错人话 },
  { 名: "空着不给参数 应失败", 参数: [], 退出码: "非零", 标准输出: "", 标准错误: 出错人话 },
  { 名: "参数不是恰好一段 应失败", 参数: ["3300开", "3300开"], 退出码: "非零", 标准输出: "", 标准错误: 出错人话 },
];

let 失败数 = 0;

for (const 例 of 用例) {
  const 第一回 = 跑一回(例.参数);
  const 第二回 = 跑一回(例.参数);

  const 问题 = [];

  if (
    第一回.退出码 !== 第二回.退出码 ||
    第一回.标准输出 !== 第二回.标准输出 ||
    第一回.标准错误 !== 第二回.标准错误
  ) {
    问题.push("连跑两次打出来的字不一样");
  }

  if (例.退出码 === "非零") {
    if (第一回.退出码 === 0 || 第一回.退出码 === null) {
      问题.push("退出码应是零以外的数，实际是 " + 第一回.退出码);
    }
  } else if (第一回.退出码 !== 例.退出码) {
    问题.push("退出码应是 " + 例.退出码 + "，实际是 " + 第一回.退出码);
  }

  if (第一回.标准输出 !== 例.标准输出) {
    问题.push(
      "标准输出应是 " + JSON.stringify(例.标准输出) +
      "，实际是 " + JSON.stringify(第一回.标准输出)
    );
  }

  if (第一回.标准错误 !== 例.标准错误) {
    问题.push(
      "标准错误应是 " + JSON.stringify(例.标准错误) +
      "，实际是 " + JSON.stringify(第一回.标准错误)
    );
  }

  if (问题.length > 0) {
    失败数 += 1;
    process.stdout.write("没过：" + 例.名 + "\n");
    for (const 条 of 问题) {
      process.stdout.write("  - " + 条 + "\n");
    }
  } else {
    process.stdout.write("通过：" + 例.名 + "\n");
  }
}

if (失败数 > 0) {
  process.stdout.write("共 " + 用例.length + " 条，没过 " + 失败数 + " 条\n");
  process.exit(1);
}
process.stdout.write("共 " + 用例.length + " 条，全部通过\n");
process.exit(0);
